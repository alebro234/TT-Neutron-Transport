"""
Graphite slab with a He-3 detector gas region, step 2/2: multigroup-mode OpenMC run with the cross sections
generated by het_ce.py.

Same slab, detector region, beam and z mesh as the CE run, but the transport uses only the MG data in mgxs.h5
(xsdata 'graphite' and 'he3': sigma_t,g, sigma_a,g, 1/v_g and the P_L scattering matrices). This solves exactly the
multigroup problem the TT solver sees, so TT vs this run isolates the solver error from the group-collapse error.

Run: python het_mg.py [P<L>] [G] [particles per batch]     (defaults: P20, 128, 100000; reads/writes results_<case>_g_<G>/)
Inputs  : mgxs.h5, het_mgxs.npz (written by het_ce.py; L, W, E0, the detector position and the group edges are taken
          from there, so the two runs cannot get out of sync)
Tallies : scalar flux on a 1 x 1 x N_z mesh in z, for every energy group (track-length estimator)
Outputs : het_mg_flux.npz, het_mg_flux.png, mg_run/ (OpenMC files)

Normalisation as in ../graphite/graphite_mg.py: phi_g(z_i) = tally / dz per unit incident beam intensity.
Legendre scattering is sampled from a tabulated version of the P_L expansion (settings.tabular_legendre);
negative parts of the truncated expansion are clipped, which a deterministic solver does not do.

Group convention (same as the TT solver): g = 0 is the HIGHEST energy group.
"""
import sys
from pathlib import Path

import numpy as np
import openmc

HERE = Path(__file__).resolve().parent
CASE = sys.argv[1] if len(sys.argv) > 1 else 'P20'
G_ARG = int(sys.argv[2]) if len(sys.argv) > 2 else 128
OUT = HERE / f'results_{CASE}_g_{G_ARG}'
MGXS_FILE = OUT / 'mgxs.h5'

# ---------------------------------------------------------------------------
# parameters (problem definition taken from the CE run)
# ---------------------------------------------------------------------------
ce = np.load(OUT / 'het_mgxs.npz')
L, W, E0 = float(ce['L']), float(ce['W']), float(ce['E0'])
Z_DET, W_DET = float(ce['z_det']), float(ce['w_det'])
N_z = int(ce['N_z'])

group_edges = openmc.MGXSLibrary.from_hdf5(str(MGXS_FILE)).energy_groups.group_edges  # ascending, eV
G = len(group_edges) - 1
assert G == G_ARG and np.allclose(group_edges[::-1], ce['group_edges_desc'])

PARTICLES = int(sys.argv[3]) if len(sys.argv) > 3 else 100_000   # per batch
BATCHES = 50
TABULAR_POINTS = 33         # points of the tabulated Legendre scattering distribution

# ---------------------------------------------------------------------------
# materials (macroscopic MG data), geometry
# ---------------------------------------------------------------------------
graphite = openmc.Material(name='graphite')
graphite.set_density('macro', 1.0)
graphite.add_macroscopic('graphite')
he3 = openmc.Material(name='he3')
he3.set_density('macro', 1.0)
he3.add_macroscopic('he3')
materials = openmc.Materials([graphite, he3])
materials.cross_sections = str(MGXS_FILE)

z_left = openmc.ZPlane(z0=0.0, boundary_type='vacuum')
z_right = openmc.ZPlane(z0=L, boundary_type='vacuum')
z_d0 = openmc.ZPlane(z0=Z_DET)
z_d1 = openmc.ZPlane(z0=Z_DET + W_DET)
x_lo = openmc.XPlane(x0=-W, boundary_type='reflective')
x_hi = openmc.XPlane(x0=W, boundary_type='reflective')
y_lo = openmc.YPlane(y0=-W, boundary_type='reflective')
y_hi = openmc.YPlane(y0=W, boundary_type='reflective')
lateral = +x_lo & -x_hi & +y_lo & -y_hi

cells = [openmc.Cell(name='graphite left', fill=graphite, region=+z_left & -z_d0 & lateral),
         openmc.Cell(name='he3 detector', fill=he3, region=+z_d0 & -z_d1 & lateral),
         openmc.Cell(name='graphite right', fill=graphite, region=+z_d1 & -z_right & lateral)]
geometry = openmc.Geometry(cells)

# ---------------------------------------------------------------------------
# source: normal beam at the left face; E0 only selects the group that contains it (g = 0)
# ---------------------------------------------------------------------------
source = openmc.IndependentSource(
    space=openmc.stats.Point((0.0, 0.0, 1.0e-8)),
    angle=openmc.stats.Monodirectional((0.0, 0.0, 1.0)),
    energy=openmc.stats.Discrete([E0], [1.0]),
)

settings = openmc.Settings()
settings.energy_mode = 'multi-group'
settings.run_mode = 'fixed source'
settings.source = source
settings.particles = PARTICLES
settings.batches = BATCHES
settings.tabular_legendre = {'enable': True, 'num_points': TABULAR_POINTS}

# ---------------------------------------------------------------------------
# tallies: scalar flux (mesh in z) x energy groups
# ---------------------------------------------------------------------------
mesh = openmc.RegularMesh(name='z mesh')
mesh.lower_left = (-W, -W, 0.0)
mesh.upper_right = (W, W, L)
mesh.dimension = (1, 1, N_z)

flux_tally = openmc.Tally(name='flux_z_E')
flux_tally.filters = [openmc.MeshFilter(mesh), openmc.EnergyFilter(group_edges)]
flux_tally.scores = ['flux']
flux_tally.estimator = 'tracklength'
tallies = openmc.Tallies([flux_tally])

# ---------------------------------------------------------------------------
# run
# ---------------------------------------------------------------------------
run_dir = OUT / 'mg_run'
run_dir.mkdir(exist_ok=True)
model = openmc.Model(geometry=geometry, materials=materials, settings=settings, tallies=tallies)
sp_path = model.run(cwd=run_dir, output=True)

# ---------------------------------------------------------------------------
# post-processing
# ---------------------------------------------------------------------------
with openmc.StatePoint(sp_path) as sp:
    t = sp.get_tally(name='flux_z_E')
    # filter order (mesh, energy); OpenMC energy bins are ascending -> reverse to g = 0 highest
    flux = t.mean.reshape(N_z, G)[:, ::-1]
    flux_sd = t.std_dev.reshape(N_z, G)[:, ::-1]

dz = L / N_z
z_centres = (np.arange(N_z) + 0.5) * dz
phi = flux / dz                     # scalar flux per unit incident beam intensity
phi_sd = flux_sd / dz

np.savez(OUT / 'het_mg_flux.npz', z=z_centres, dz=dz, L=L, group_edges_desc=group_edges[::-1],
         phi=phi, phi_sd=phi_sd, E0=E0, region_map=ce['region_map'])

# ---------------------------------------------------------------------------
# plot: every 16th group (128 curves are unreadable), detector region shaded
# ---------------------------------------------------------------------------
import matplotlib.pyplot as plt

fig, ax = plt.subplots(figsize=(9, 6))
E_hi = group_edges[::-1]
cols = plt.cm.viridis(np.linspace(0, 0.95, G))
for g in range(0, G, max(1, G // 8)):
    ax.semilogy(z_centres, phi[:, g], color=cols[g], label=f'g={g}: {E_hi[g+1]:.2e}-{E_hi[g]:.2e} eV')
    ax.fill_between(z_centres, phi[:, g] - phi_sd[:, g], phi[:, g] + phi_sd[:, g], color=cols[g], alpha=0.2)
ax.axvspan(Z_DET, Z_DET + W_DET, color='0.85', zorder=0, label='He-3')
ax.set_xlabel('z [cm]')
ax.set_ylabel(r'scalar flux $\phi_g(z)$ per unit beam intensity')
ax.set_title(f'graphite slab + He-3 (OpenMC MG, {CASE}, G = {G}), L = {L} cm, {E0/1e6:g} MeV normal beam')
ax.grid(True, which='both')
ax.legend(fontsize=8)
plt.tight_layout()
plt.savefig(OUT / 'het_mg_flux.png', dpi=150)
plt.show()
