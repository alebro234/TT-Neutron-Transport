"""
Graphite slab, step 2/2: multigroup-mode OpenMC run with the cross sections generated by graphite_ce.py.

Same slab, beam and z mesh as the CE run, but the transport uses only the MG data in mgxs.h5
(sigma_t,g, sigma_a,g, 1/v_g and the P_L scattering matrix). This solves exactly the multigroup problem
the TT solver sees, so TT vs this run isolates the solver error from the group-collapse error.

Run: python graphite_mg.py P0tr|P7 [particles per batch]   (reads/writes results_<case>/)
Inputs  : mgxs.h5, graphite_mgxs.npz (written by graphite_ce.py; L, W, E0 and the group edges are taken
          from there, so the two runs cannot get out of sync)
Tallies : scalar flux on a 1 x 1 x N_z mesh in z, for every energy group (track-length estimator)
          [optional: time bins, for the time-dependent comparison]
Outputs : graphite_mg_flux.npz, graphite_mg_flux.png (next to this script), mg_run/ (OpenMC files)

Normalisation of the flux: OpenMC returns track length per source particle in each mesh cell.
For a plane beam of unit intensity (1 particle / cm^2 / source) the scalar flux is
    phi_g(z_i) = tally / dz            [particles cm^-2 per unit incident particle per cm^2]
(the transverse area cancels because the side planes are reflective).
With time bins the tally is integrated over each bin: divide by the bin width for phi_g(z, t).

Legendre scattering is sampled from a tabulated version of the P_L expansion
(settings.tabular_legendre); negative parts of the truncated expansion are clipped, which a
deterministic solver does not do -> check convergence in L_max if group differences appear.

Group convention (same as the TT solver): g = 0 is the HIGHEST energy group.
"""
from pathlib import Path

import numpy as np
import openmc

import sys
HERE = Path(__file__).resolve().parent
CASE = sys.argv[1] if len(sys.argv) > 1 else 'P7'
OUT = HERE / f'results_{CASE}'
MGXS_FILE = OUT / 'mgxs.h5'

# ---------------------------------------------------------------------------
# parameters (problem definition taken from the CE run)
# ---------------------------------------------------------------------------
ce = np.load(OUT / 'graphite_mgxs.npz')
L = float(ce['L'])
W = float(ce['W'])
E0 = float(ce['E0'])

group_edges = openmc.MGXSLibrary.from_hdf5(str(MGXS_FILE)).energy_groups.group_edges  # ascending, eV
G = len(group_edges) - 1
assert np.allclose(group_edges[::-1], ce['group_edges_desc'])

N_z = 200                   # mesh cells in z
PARTICLES = int(sys.argv[2]) if len(sys.argv) > 2 else 100_000   # per batch
BATCHES = 50
TIME_EDGES = None           # e.g. np.linspace(0, 1e-6, 21) [s] to add time bins to the flux tally
TABULAR_POINTS = 33         # points of the tabulated Legendre scattering distribution

# ---------------------------------------------------------------------------
# material (macroscopic MG data), geometry
# ---------------------------------------------------------------------------
graphite = openmc.Material(name='graphite')
graphite.set_density('macro', 1.0)
graphite.add_macroscopic('graphite')
materials = openmc.Materials([graphite])
materials.cross_sections = str(MGXS_FILE)

z_left = openmc.ZPlane(z0=0.0, boundary_type='vacuum')
z_right = openmc.ZPlane(z0=L, boundary_type='vacuum')
x_lo = openmc.XPlane(x0=-W, boundary_type='reflective')
x_hi = openmc.XPlane(x0=W, boundary_type='reflective')
y_lo = openmc.YPlane(y0=-W, boundary_type='reflective')
y_hi = openmc.YPlane(y0=W, boundary_type='reflective')

slab = openmc.Cell(name='slab', fill=graphite,
                   region=+z_left & -z_right & +x_lo & -x_hi & +y_lo & -y_hi)
geometry = openmc.Geometry([slab])

# ---------------------------------------------------------------------------
# source: normal beam at the left face; E0 only selects the group that contains it (g = 0)
# ---------------------------------------------------------------------------
source = openmc.IndependentSource(
    space=openmc.stats.Point((0.0, 0.0, 1.0e-8)),
    angle=openmc.stats.Monodirectional((0.0, 0.0, 1.0)),
    energy=openmc.stats.Discrete([E0], [1.0]),
)

settings = openmc.Settings()
settings.energy_mode = 'multi-group'
settings.run_mode = 'fixed source'
settings.source = source
settings.particles = PARTICLES
settings.batches = BATCHES
settings.tabular_legendre = {'enable': True, 'num_points': TABULAR_POINTS}

# ---------------------------------------------------------------------------
# tallies: scalar flux (mesh in z) x energy groups [x time]
# ---------------------------------------------------------------------------
mesh = openmc.RegularMesh(name='z mesh')
mesh.lower_left = (-W, -W, 0.0)
mesh.upper_right = (W, W, L)
mesh.dimension = (1, 1, N_z)

flux_filters = [openmc.MeshFilter(mesh), openmc.EnergyFilter(group_edges)]
if TIME_EDGES is not None:
    flux_filters.append(openmc.TimeFilter(TIME_EDGES))

flux_tally = openmc.Tally(name='flux_z_E')
flux_tally.filters = flux_filters
flux_tally.scores = ['flux']
flux_tally.estimator = 'tracklength'

tallies = openmc.Tallies([flux_tally])

# ---------------------------------------------------------------------------
# run
# ---------------------------------------------------------------------------
run_dir = OUT / 'mg_run'
run_dir.mkdir(exist_ok=True)
model = openmc.Model(geometry=geometry, materials=materials, settings=settings, tallies=tallies)
sp_path = model.run(cwd=run_dir, output=True)

# ---------------------------------------------------------------------------
# post-processing
# ---------------------------------------------------------------------------
with openmc.StatePoint(sp_path) as sp:
    t = sp.get_tally(name='flux_z_E')
    shape = [N_z, G] + ([len(TIME_EDGES) - 1] if TIME_EDGES is not None else [])
    # filter order (mesh, energy[, time]); OpenMC energy bins are ascending -> reverse to g = 0 highest
    flux = t.mean.reshape(shape)[:, ::-1, ...]
    flux_sd = t.std_dev.reshape(shape)[:, ::-1, ...]

dz = L / N_z
z_centres = (np.arange(N_z) + 0.5) * dz
phi = flux / dz                     # scalar flux per unit incident beam intensity
phi_sd = flux_sd / dz

np.savez(OUT / 'graphite_mg_flux.npz',
         z=z_centres, dz=dz, L=L, group_edges_desc=group_edges[::-1],
         phi=phi, phi_sd=phi_sd,
         time_edges=TIME_EDGES if TIME_EDGES is not None else np.array([]),
         E0=E0)

# ---------------------------------------------------------------------------
# plot (steady state, or the last time bin)
# ---------------------------------------------------------------------------
import matplotlib.pyplot as plt

phi_plot = phi if TIME_EDGES is None else phi[..., -1]
sd_plot = phi_sd if TIME_EDGES is None else phi_sd[..., -1]
fig, ax = plt.subplots(figsize=(9, 6))
E_hi = group_edges[::-1]
for g in range(G):
    ax.semilogy(z_centres, phi_plot[:, g], label=f'g={g}: {E_hi[g+1]:.2e}-{E_hi[g]:.2e} eV')
    ax.fill_between(z_centres, phi_plot[:, g] - sd_plot[:, g], phi_plot[:, g] + sd_plot[:, g], alpha=0.2)
ax.set_xlabel('z [cm]')
ax.set_ylabel(r'scalar flux $\phi_g(z)$ per unit beam intensity')
ax.set_title(f'graphite slab (OpenMC MG, {CASE}), L = {L} cm, {E0/1e6:g} MeV normal beam')
ax.grid(True, which='both')
ax.legend(fontsize=8)
plt.tight_layout()
plt.savefig(OUT / 'graphite_mg_flux.png', dpi=150)

